DIALOGUE_GUIDE = """
## 对话写作指南

### 潜台词五层
1. 情感潜台词 — 表面平静，内里汹涌。「你来了。」= 期待已久/冷淡疏离
2. 动机潜台词 — 每句话背后有目的。「最近过得怎么样？」= 试探/关心/找话题
3. 关系潜台词 — 称呼变化暗示关系。「王总」→「老王」→「你」
4. 情节潜台词 — 话里有推进。「这件事，我会处理的。」= 即将行动/敷衍/威胁
5. 主题潜台词 — 日常对话折射主题。「人各有命。」= 宿命/无奈/反讽

### 对话设计铁律
- 有人抢话、有人沉默、有人答非所问
- 角色不会把真实想法全盘托出
- 不同角色有不同的说话节奏（啰嗦/惜字如金）
- said tag 不超过 30%，优先用前置动作（「他把烟掐灭——'行。'」）
- 删掉「XX说道」「XX淡淡道」，改为动作引导

### 严格禁止
- A说→B说→A说→B说 的乒乓球对话
- 每句都完整回应上一句
- 角色说话像在做报告
- 对话用于解释背景（用行动和冲突替代）
"""

SCENE_GUIDE = """
## 场景描写指南

### 五感层次（按重要性排序）
1. 视觉 — 动作轨迹、光影色彩、环境变化、表情与姿态
2. 听觉 — 对话声、碰撞声、呼吸心跳、沉默的压迫感
3. 触觉 — 温度（冷/热）、力度（轻/重）、质感（滑/糙）、动态
4. 嗅觉 — 体香标记身份、气息传递吸引力、环境气味营造氛围
5. 味觉 — 直接（食物）、隐喻（苦涩甜蜜）、情感表达

### 感官交织方法
- 并列式：多感官同时呈现 →「他的手指划过她的脸颊（触），带着淡淡烟草味（嗅），她听到心跳加速（听）」
- 递进式：感官强度逐步升级 → 若有若无香气 → 指尖轻触 → 灼热呼吸
- 对比式：不同感官形成对比 →「外面刺骨寒风，怀里温暖如春」

### 场景类型感官重点
- 战斗：视觉+听觉+触觉 → 动作轨迹、碰撞声、冲击感
- 情感：触觉+嗅觉+听觉 → 肌肤接触、体香、呼吸心跳
- 环境：视觉+听觉+嗅觉 → 景色光影、环境音、气味
- 恐怖：听觉+触觉+视觉 → 诡异声音、阴冷触感、阴暗光影

### 铁律
- 网文场景描写要「适度」——太少无画面感，太多拖节奏
- 描写服务于情感和氛围，不是为描写而描写
"""

COMBAT_GUIDE = """
## 战斗场面写作指南

### 五阶段结构
| 阶段 | 篇幅 | 内容 | 节奏 |
| 起手 | 15-20% | 对峙试探、环境氛围、心理博弈 | 慢 |
| 试探 | 20-25% | 初步交手、实力试探、能力展示 | 渐快 |
| 冲突升级 | 30-40% | 正式交锋、底牌亮出、战局变化 | 快 |
| 高潮 | 15-20% | 关键转折、决定性一击 | 极快 |
| 收尾 | 10-15% | 胜负分晓、后续影响、气氛收束 | 慢 |

### 战斗类型与字数
- 秒杀：50-100字，极快，碾压快感
- 碾压：200-300字，快，装逼打脸
- 势均力敌：500-800字，中速，绝地反击
- 苦战：800-1500字，慢，爆发逆转
- 大战：2000字+，多段，多重高潮

### 节奏控制
- 快节奏：短句 + 动作密集 + 快速切换 →「一拳。后退三步。又一拳。胸骨碎裂。」
- 慢节奏：长句 + 细节描写 + 心理活动 → 对峙蓄力、暗流涌动
- 节奏曲线：慢（对峙）→快（交手）→慢（喘息）→快（爆发）→慢（结束）

### 画面切换
- 远景 → 战场全貌、势力对比
- 近景 → 详细动作与微表情
- 特写 → 关键瞬间放大（拳拳到肉、武器碰撞）
"""

EMOTION_GUIDE = """
## 情感与心理描写指南

### 心理描写三层次
1. 意识层面 — 角色能意识到的心理 →「他知道不该这样想，但还是忍不住」
2. 潜意识层面 — 隐约感觉但不愿面对 →「她告诉自己只是朋友，却总不自觉看向他」
3. 无意识流露 — 角色自己没意识到的泄露 →「'我没事。'攥紧的拳头出卖了她」

### 五大技巧
1. 直接内心独白 — 关键情绪节点用，每段不超过3句
2. 间接心理描写 — 通过行为/表情/对话展现
3. 感官触发心理 — 熟悉的香水味飘来，心猛地一紧
4. 梦境折射心理 — 梦到她转身离去，拼命追却追不上
5. 自由联想 — 看着窗外的雨，想起那天，想起眼泪，想起懦弱

### 情绪变化曲线
- 递进：不安→担忧→恐惧→绝望；好感→心动→喜欢→深爱
- 转折：愤怒→震惊→理解→释然；期待→失望→愤怒→冷漠
- 混合：表面愤怒内心担忧、表面冷静内心狂喜

### 铁律
- 情绪是「展示」不是「贴标签」
- 删掉「他感到愤怒」→ 改为生理反应+微动作
- 情绪切换必须有过渡 →「他压下怒意，但声音还是哑了半拍」
- 避免全员同一套反应（瞳孔微缩/心中一凛）
"""

DESIRE_GUIDE = """
## 欲念描写指南

### 核心原则
感官描写服务于情感表达
情节推进优先于感官刺激
文学美感与感官体验平衡
暗示留白胜过直白描写

### 尺度法则
暗示 > 描写
情感 > 感官
美感 > 刺激

### 五感重点
- 触觉：温度（滚烫/冰凉）、质感（丝滑/粗粝）、压力（轻抚/紧握）、电流感（酥麻/颤栗）
- 嗅觉：体香（亲密标记）、气息（温热呼吸）、环境香（檀香/花香）
- 听觉：呼吸声（急促/平稳）、心跳声（砰砰/漏拍）、低语（耳畔呢喃）
- 视觉：眼神（深邃/迷离/炽热）、表情（微红/咬唇）、动作（轻颤/僵硬）

### 情感渐进式描写
阶段一：意识萌芽 — 发现自己在看他，慌乱移开视线
阶段二：身体反应 — 心跳加速，指尖微颤，不受控制
阶段三：无法忽视 — 每个细胞都在呼唤，理智开始松动
阶段四：情绪占据 — 世界缩小到只有两个人
阶段五：交付/爆发 — 不再抵抗，完整的信任与交付
"""

ANTI_AI_INSTRUCTIONS = """
## 去AI味写作指令（必须遵守）

你作为 LLM 有根深蒂固的写作癖好。刻意对抗以下倾向：

1. **禁止四段闭环** — 不要「起因→经过→结果→感悟」。删掉最后的感悟/总结句，留未解决的余味。
2. **禁止万能副词** — 不要「缓缓开口」「淡淡说道」「微微点头」「轻轻摇头」。全部删掉副词，用具体动作替代。宁可写「他把杯子搁下——'你确定？'」也不写「他缓缓放下杯子——'你确定？'」。如果你忍不住写了「微微」「缓缓」「轻轻」「淡淡」，立刻删掉重写。
3. **禁止全员同一反应** — 不要每个人都「瞳孔微缩」「心中一凛」。给每个角色设计专属微动作。
4. **禁止对话像辩论** — 不要让角色完整、理性地表达观点。加潜台词、言行不一、省略和打断。
5. **禁止情绪贴标签** — 不要写「他感到愤怒」。改为生理反应+微动作，让读者自己判断。
6. **禁止信息均匀分布** — 刻意制造疏密对比，有的段落只有一句话，有的段落十几句。
7. **禁止安全着陆** — 章末不要解决所有冲突。至少留一个未解决的问题。
8. **禁止展示后解释** — 写完「她把门摔上」后不要再写「她显然很生气」。信任读者。

### 替换速查
- 「他感到愤怒」→ 生理+微动作+决策：「指节捏得发白，舌尖尝到铁锈味」
- 「缓缓说道」→ 删副词+前置动作：「他搁下杯子——'你确定？'」
- 「眸中闪过一丝X」→ 个性化行为：「她咬了下嘴唇内侧」
- 「心中暗道」→ 删掉这四个字，后面的内心句直接保留
- 「更重要的是……」→ 直接说事，删递进模板词
- 「XX淡淡道」→ 动作引导：「他没抬头——'随你。'」

### 每写完一段自查
1. 这段走完了「起因→经过→结果→感悟」吗？→ 删掉感悟句
2. 最近3个动作用了「缓缓/淡淡/微微」吗？→ 换成具体动作
3. 情绪是「告诉」还是「展示」？→ 改为生理反应
4. 对话在推进冲突还是在解释背景？→ 删解释，加入真实意图
5. 最近500字节奏均匀吗？→ 插入短句爆发点或一段沉默
"""

STYLE_CONSTRAINTS = """
## 风格约束（必须遵守）

### 硬约束
- 长句（>40字）必须拆分，连续长句不得超过2句
- 抽象判断改为动作/反应/代价 → 不写「局势很危险」，写「剑锋擦过耳际，削断三根头发」
- 删除「总结式旁白」和大段纯解释（连续解释不超过100字）
- 每章必须有至少1个明确推进点：信息/行动/关系/局势其一

### 软建议（优先执行）
- 开头200-400字内进入冲突/风险/强情绪
- 章末设置未闭合问题/期待锚点
- 每章至少1处「可量化变化」（地位/资源/关系/风险）
- 对话保持「意图冲突」，减少无效寒暄
- 钩子优先「选择钩/危机钩」

### 分题材风格加权
- 玄幻/修仙/高武：动作与结果比重更高，术语解释后置
- 都市/直播/电竞：信息节奏更快，强化「反馈→反应→反制」三连
- 言情/替身/狗血：情绪弧线前置，关键场景必须有关系位移
- 悬疑/规则怪谈/克苏鲁：线索投放要可回收，恐惧来自规则而非堆词
"""

# ============================================================
# 指南分发逻辑
# ============================================================

# 章节类型 → 指南映射
CHAPTER_TYPE_GUIDES = {
    "combat": COMBAT_GUIDE,
    "dialogue": DIALOGUE_GUIDE,
    "emotional": EMOTION_GUIDE,
    "desire": DESIRE_GUIDE,
    "transition": SCENE_GUIDE,
    "normal": SCENE_GUIDE,
}

# 题材 → 风格加权映射（与 genre_templates 表对齐）
GENRE_STYLE_KEYS = {
    "xianxia": "玄幻/修仙/高武",
    "xuanhuan": "玄幻/修仙/高武",
    "high_martial": "玄幻/修仙/高武",
    "urban": "都市/直播/电竞",
    "urban_brainhole": "都市/直播/电竞",
    "esports": "都市/直播/电竞",
    "live_stream": "都市/直播/电竞",
    "romance": "言情/替身/狗血",
    "guyan": "言情/替身/狗血",
    "substitute": "言情/替身/狗血",
    "dog_blood": "言情/替身/狗血",
    "suspense": "悬疑/规则怪谈/克苏鲁",
    "horror": "悬疑/规则怪谈/克苏鲁",
    "cthulhu": "悬疑/规则怪谈/克苏鲁",
    "rule_strange": "悬疑/规则怪谈/克苏鲁",
    "scifi": "都市/直播/电竞",  # 科幻节奏接近都市
    "post_apocalyptic": "悬疑/规则怪谈/克苏鲁",  # 末世接近悬疑
}


def get_writing_guide(chapter_type: str = "normal") -> str:
    """
    按章节类型返回对应的写作指南。
    
    Args:
        chapter_type: combat / dialogue / emotional / desire / transition / normal
    
    Returns:
        对应的写作指南文本（中文）
    """
    return CHAPTER_TYPE_GUIDES.get(chapter_type, SCENE_GUIDE)


def get_combined_guides(types: list[str]) -> str:
    """
    合并多种类型的指南（如 combat+emotional）。
    去重拼接，避免重复注入相同的通用指南。
    """
    guides = []
    seen = set()
    for t in types:
        guide = CHAPTER_TYPE_GUIDES.get(t)
        if guide and t not in seen:
            guides.append(guide)
            seen.add(t)
    return "\n".join(guides)


def get_anti_ai_instructions() -> str:
    """返回去 AI 味写作指令"""
    return ANTI_AI_INSTRUCTIONS


def get_style_constraints(genre: Optional[str] = None) -> str:
    """
    返回风格约束，可选按题材加权。
    
    Args:
        genre: 题材标识（如 'xianxia', 'urban', 'suspense'）
    
    Returns:
        风格约束文本，含对应题材的加权提示
    """
    base = STYLE_CONSTRAINTS
    if genre and genre in GENRE_STYLE_KEYS:
        tag = GENRE_STYLE_KEYS[genre]
        # 在分题材加权段高亮对应行
        base += f"\n**当前题材：{tag}** — 上述分题材加权中，属于「{tag}」类的约束请严格优先执行。"
    return base


def build_writing_prompt_section(
    chapter_type: str = "normal",
    genre: Optional[str] = None,
    include_anti_ai: bool = True,
    include_style: bool = True,
) -> str:
    """
    组装完整的写作质量 prompt 段。
    
    这是 generate_chapter_stream 调用入口。
    返回拼接好的中文指令块，直接注入 system prompt。
    
    Args:
        chapter_type: 章节类型
        genre: 题材标识
        include_anti_ai: 是否注入去 AI 味指令
        include_style: 是否注入风格约束
    
    Returns:
        完整的写作指令文本块
    """
    sections = []

    if include_anti_ai:
        sections.append(ANTI_AI_INSTRUCTIONS)

    if include_style:
        sections.append(get_style_constraints(genre))

    guide = get_writing_guide(chapter_type)
    sections.append(guide)

    return "\n\n".join(sections)